# ============ 测试用例 ============
def run_tests():
    sol = Solution()
    cases = [
        # (输入参数..., 期望输出, 说明)
        (["2", "1", "+", "3", "*"], 9, "示例 1"),
        (["4", "13", "5", "/", "+"], 6, "示例 2：13/5 向零截断为 2"),
        (
            ["10", "6", "9", "3", "+", "-11", "*", "/", "*", "17", "+", "5", "+"],
            22,
            "示例 3：6/-132 截断为 0",
        ),
        (["3"], 3, "最小规模：只有一个数"),
        (["-7"], -7, "单个负数（不能把 '-' 开头的数当成算符）"),
        (["3", "4", "-"], -1, "减法顺序：次栈顶 - 栈顶"),
        (["8", "2", "/"], 4, "除法顺序：次栈顶 / 栈顶"),
        (["-7", "2", "/"], -3, "负数除法向零截断（不是向下取整的 -4）"),
        (["7", "-2", "/"], -3, "除数为负，同样向零截断"),
        (["0", "3", "/"], 0, "被除数为 0"),
    ]
    passed = 0
    for i, (*args, expected, desc) in enumerate(cases, 1):
        got = sol.evalRPN(*args)
        ok = got == expected
        passed += ok
        print(f"[{'PASS' if ok else 'FAIL'}] #{i} {desc}: 期望 {expected}, 实际 {got}")
    print(f"\n{passed}/{len(cases)} 通过")


if __name__ == "__main__":
    run_tests()
